import { writeFileSync } from "node:fs";

import { routes } from "../src/simulation/seed/geography.ts";
import { getPairDistanceMeters } from "../src/utils/geo.ts";

const token = process.env.MAPBOX_TOKEN ?? process.env.EXPO_PUBLIC_MAPBOX_TOKEN;
if (!token) throw new Error("Set MAPBOX_TOKEN in .env to bake road geometry.");

const maxCoordinates = 25;
const isDetour = (roadMeters, straightMeters) =>
  roadMeters > straightMeters * 1.6 + 60;

async function requestLegs(points) {
  const coordinates = points.map(([lat, lng]) => `${lng},${lat}`).join(";");
  const url = `https://api.mapbox.com/directions/v5/mapbox/driving/${coordinates}?geometries=geojson&overview=false&steps=true&access_token=${encodeURIComponent(token)}`;
  const response = await fetch(url);
  const data = await response.json();
  const legs = data.routes?.[0]?.legs;
  if (data.code !== "Ok" || !legs) throw new Error(data.message ?? "No route found.");
  return legs;
}

async function followRoads(points) {
  const out = [];
  for (let start = 0; start < points.length - 1; start += maxCoordinates - 1) {
    const chunk = points.slice(start, start + maxCoordinates);
    const legs = await requestLegs(chunk);
    legs.forEach((leg, index) => {
      const a = chunk[index];
      const b = chunk[index + 1];
      const coords = (leg.steps ?? []).flatMap((step) => step.geometry?.coordinates ?? []);
      const segment =
        !coords.length || isDetour(leg.distance ?? 0, getPairDistanceMeters(a, b))
          ? [a, b]
          : coords.map(([lng, lat]) => [lat, lng]);
      for (const point of segment) {
        const last = out[out.length - 1];
        if (!last || last[0] !== point[0] || last[1] !== point[1]) out.push(point);
      }
    });
  }
  return out.map(([lat, lng]) => [Number(lat.toFixed(6)), Number(lng.toFixed(6))]);
}

const asPaths = (value) => {
  if (!Array.isArray(value) || !value.length) return [];
  return typeof value[0][0] === "number" ? [value] : value;
};

const baked = {};
for (const route of routes) {
  const path = route.path;
  if (!Array.isArray(path) || path.length < 2) continue;
  const roadPath = await followRoads(path);
  const alternatives = [];
  for (const alt of asPaths(route.alternative_paths)) alternatives.push(await followRoads(alt));
  baked[String(route.route_id)] = { path: roadPath, alternatives };
  console.log(`${route.route_code}: ${path.length} -> ${roadPath.length} points, ${alternatives.length} alternatives`);
}

const body = `// Generated by scripts/bake-road-geometry.mjs — do not edit.
export const roadGeometry: Record<string, { path: [number, number][]; alternatives: [number, number][][] }> = ${JSON.stringify(baked)};
`;
writeFileSync(new URL("../src/simulation/seed/road-geometry.generated.ts", import.meta.url), body);
console.log("Wrote src/simulation/seed/road-geometry.generated.ts");
